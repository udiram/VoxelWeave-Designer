#!/usr/bin/env python3
"""Qualify representative operations through the real VoxelWeave sidecar.

This is an engine/sidecar benchmark, not a browser frame-rate test.  It uses a
synthetic but complete DICOM series generated by the current engine, runs the
same JSONL operations used by the desktop adapter, records p50/p95/max timing,
and fails only when a generous severe-regression gate is exceeded.  Product UI
targets that require WebKit, Three.js, or Instruments remain explicitly
unmeasured here.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import platform
import selectors
import subprocess
import sys
import time
from pathlib import Path
from tempfile import TemporaryDirectory
from typing import Any, Iterable


ROOT = Path(__file__).resolve().parents[1]
PROTOCOL = "voxelweave.control.v1"
RESPONSE_PROTOCOL = "voxelweave.response.v1"


class BenchmarkFailure(RuntimeError):
    """Raised when a benchmark operation or release gate fails."""


def percentile(values: Iterable[float], quantile: float) -> float:
    """Return a nearest-rank percentile for a non-empty sample."""

    samples = sorted(float(value) for value in values)
    if not samples:
        raise ValueError("percentile requires at least one sample")
    if not 0.0 <= quantile <= 1.0:
        raise ValueError("quantile must be between 0 and 1")
    index = max(0, min(len(samples) - 1, math.ceil(quantile * len(samples)) - 1))
    return samples[index]


def _calibration() -> list[dict[str, Any]]:
    return [
        {
            "calibration_id": "native-performance-t0",
            "binding": {
                "pitch_mm": 4.0,
                "layer_height_mm": 0.2,
                "nozzle_mm": 0.25,
                "tool": "T0",
                "material": "Natural PLA",
                "lot": "synthetic",
                "printer": "Prusa XL",
                "scanner": "synthetic CT",
                "reconstruction": "STANDARD / BONE",
                "flow_mm3_s": 1.0,
            },
            "commanded_width_mm": [0.48, 0.62, 0.82, 1.02],
            "measured_hu_mean": [-872, -824, -742, -680],
            "accepted": True,
        }
    ]


class SidecarClient:
    def __init__(self, command: list[str], *, request_timeout_seconds: float) -> None:
        environment = os.environ.copy()
        source_path = str(ROOT / "engine" / "src")
        environment["PYTHONPATH"] = source_path + os.pathsep + environment.get("PYTHONPATH", "")
        environment["PYTHONUNBUFFERED"] = "1"
        try:
            self.process = subprocess.Popen(
                command,
                stdin=subprocess.PIPE,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                env=environment,
            )
        except OSError as error:
            raise BenchmarkFailure(f"cannot start sidecar {' '.join(command)}: {error}") from error
        self.request_timeout_seconds = request_timeout_seconds
        self._counter = 0

    def request(self, operation: str, payload: dict[str, Any]) -> tuple[dict[str, Any], float, float | None, int]:
        if self.process.stdin is None or self.process.stdout is None:
            raise BenchmarkFailure("sidecar pipes were not available")
        self._counter += 1
        request_id = f"native-perf-{self._counter}"
        envelope = {"protocol": PROTOCOL, "request_id": request_id, "operation": operation, "payload": payload}
        encoded = (json.dumps(envelope, sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8")
        started = time.perf_counter()
        self.process.stdin.write(encoded)
        self.process.stdin.flush()
        first_progress_ms: float | None = None
        progress_count = 0
        selector = selectors.DefaultSelector()
        selector.register(self.process.stdout, selectors.EVENT_READ)
        buffer = bytearray()
        deadline = started + self.request_timeout_seconds
        try:
            while time.perf_counter() < deadline:
                if not selector.select(max(0.01, deadline - time.perf_counter())):
                    continue
                chunk = os.read(self.process.stdout.fileno(), 65536)
                if not chunk:
                    stderr = self.process.stderr.read().decode("utf-8", errors="replace") if self.process.stderr else ""
                    raise BenchmarkFailure(f"sidecar exited while measuring {operation}; stderr={stderr[-4000:]!r}")
                buffer.extend(chunk)
                while b"\n" in buffer:
                    raw, _, remainder = buffer.partition(b"\n")
                    buffer = bytearray(remainder)
                    if not raw.strip():
                        continue
                    try:
                        value = json.loads(raw)
                    except json.JSONDecodeError as error:
                        raise BenchmarkFailure(f"sidecar emitted invalid JSON for {operation}: {error}") from error
                    elapsed_ms = (time.perf_counter() - started) * 1000
                    if value.get("protocol") == "voxelweave.progress.v1":
                        progress_count += 1
                        if first_progress_ms is None:
                            first_progress_ms = elapsed_ms
                        continue
                    if value.get("protocol") != RESPONSE_PROTOCOL or value.get("request_id") != request_id:
                        raise BenchmarkFailure(f"response correlation failed for {operation}: {value}")
                    if not value.get("ok"):
                        raise BenchmarkFailure(f"{operation} returned an error: {value.get('error')}")
                    return value, elapsed_ms, first_progress_ms, progress_count
        finally:
            selector.close()
        raise BenchmarkFailure(f"timed out after {self.request_timeout_seconds:.1f}s measuring {operation}")

    def close(self) -> None:
        if self.process.stdin is not None:
            try:
                self.process.stdin.close()
            except OSError:
                pass
        if self.process.poll() is None:
            self.process.terminate()
            try:
                self.process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=5)


def _require_payload(response: dict[str, Any], operation: str) -> dict[str, Any]:
    payload = response.get("payload")
    if not isinstance(payload, dict):
        raise BenchmarkFailure(f"{operation} returned no object payload")
    return payload


def _record(records: dict[str, list[float]], operation: str, elapsed_ms: float, first_progress_ms: float | None) -> None:
    records.setdefault(f"{operation}_elapsed_ms", []).append(elapsed_ms)
    if first_progress_ms is not None:
        records.setdefault(f"{operation}_first_progress_ms", []).append(first_progress_ms)


def _run_iteration(command: list[str], iteration_dir: Path, request_timeout_seconds: float) -> tuple[dict[str, list[float]], dict[str, Any]]:
    records: dict[str, list[float]] = {}
    details: dict[str, Any] = {"operations": {}}
    launch_started = time.perf_counter()
    client = SidecarClient(command, request_timeout_seconds=request_timeout_seconds)
    try:
        response, elapsed, first_progress, progress_count = client.request(
            "validate_scene", {"scene": {"regions": [{"id": "native-perf", "owner": "T0:measurement"}]}}
        )
        if _require_payload(response, "validate_scene").get("passed") is not True:
            raise BenchmarkFailure("validate_scene did not pass")
        launch_elapsed = (time.perf_counter() - launch_started) * 1000
        records["launch_to_first_response_ms"] = [launch_elapsed]
        _record(records, "validate_scene", elapsed, first_progress)
        details["operations"]["validate_scene"] = {"elapsedMs": elapsed, "progressEvents": progress_count}

        response, elapsed, first_progress, progress_count = client.request(
            "inspect_dicom_source", {"source": "synthetic://voxelweave/native-performance"}
        )
        if not _require_payload(response, "inspect_dicom_source").get("series"):
            raise BenchmarkFailure("synthetic inspection did not return series metadata")
        _record(records, "inspect_dicom_source", elapsed, first_progress)
        details["operations"]["inspect_dicom_source"] = {"elapsedMs": elapsed, "firstProgressMs": first_progress, "progressEvents": progress_count}

        response, elapsed, first_progress, progress_count = client.request(
            "select_dicom_series", {"source": "synthetic://voxelweave/native-performance"}
        )
        if not _require_payload(response, "select_dicom_series").get("eligible"):
            raise BenchmarkFailure("synthetic series selection did not return an eligible series")
        _record(records, "select_dicom_series", elapsed, first_progress)
        details["operations"]["select_dicom_series"] = {"elapsedMs": elapsed, "progressEvents": progress_count}

        response, elapsed, first_progress, progress_count = client.request(
            "build_volume_cache", {"directory": str(iteration_dir / "cache")}
        )
        if not _require_payload(response, "build_volume_cache").get("scientific_source"):
            raise BenchmarkFailure("volume cache did not retain the scientific source")
        _record(records, "build_volume_cache", elapsed, first_progress)
        details["operations"]["build_volume_cache"] = {"elapsedMs": elapsed, "firstProgressMs": first_progress, "progressEvents": progress_count}

        response, elapsed, first_progress, progress_count = client.request(
            "request_mpr_plane",
            {"plane": "axial", "index": 5, "output_shape_yx": [32, 40], "output_path": "perf-mpr.bin"},
        )
        if not _require_payload(response, "request_mpr_plane").get("artifact"):
            raise BenchmarkFailure("MPR request did not return an artifact")
        _record(records, "uncached_mpr", elapsed, first_progress)
        details["operations"]["uncached_mpr"] = {"elapsedMs": elapsed, "progressEvents": progress_count}

        response, elapsed, first_progress, progress_count = client.request(
            "request_volume_preview", {"max_dimension": 32, "output_path": "perf-preview.bin"}
        )
        if not _require_payload(response, "request_volume_preview").get("artifact"):
            raise BenchmarkFailure("volume preview did not return an artifact")
        _record(records, "request_volume_preview", elapsed, first_progress)
        details["operations"]["request_volume_preview"] = {"elapsedMs": elapsed, "progressEvents": progress_count}

        response, elapsed, first_progress, progress_count = client.request(
            "create_print_selection",
            {
                "plane": "axial",
                "mode": "continuous",
                "start_index": 1,
                "end_index": 8,
                "print_size_mm": [24, 24, 8],
                "layer_height_mm": 0.2,
                "stride": 1,
            },
        )
        if not _require_payload(response, "create_print_selection").get("mode"):
            raise BenchmarkFailure("print selection did not return a mode")
        _record(records, "create_print_selection", elapsed, first_progress)
        details["operations"]["create_print_selection"] = {"elapsedMs": elapsed, "progressEvents": progress_count}

        response, elapsed, first_progress, progress_count = client.request(
            "generate_toolpath",
            {
                "calibration": _calibration(),
                "tool": "T0",
                "allow_calibration_clipping": True,
                "acknowledge_calibration_clipping": True,
                "profile": {"printer": "Prusa XL", "sample_step_mm": 2.0},
            },
        )
        generated = _require_payload(response, "generate_toolpath")
        if not generated.get("gcode_sha256"):
            raise BenchmarkFailure("toolpath generation did not return a G-code hash")
        _record(records, "generate_toolpath", elapsed, first_progress)
        details["operations"]["generate_toolpath"] = {"elapsedMs": elapsed, "firstProgressMs": first_progress, "progressEvents": progress_count}

        response, elapsed, first_progress, progress_count = client.request("reverse_audit_gcode", {})
        if _require_payload(response, "reverse_audit_gcode").get("passed") is not True:
            raise BenchmarkFailure("reverse audit did not pass")
        _record(records, "reverse_audit_gcode", elapsed, first_progress)
        details["operations"]["reverse_audit_gcode"] = {"elapsedMs": elapsed, "progressEvents": progress_count}

        response, elapsed, first_progress, progress_count = client.request(
            "export_run_package", {"directory": str(iteration_dir / "run-package")}
        )
        if not _require_payload(response, "export_run_package").get("hashes"):
            raise BenchmarkFailure("run package export did not return hashes")
        _record(records, "export_run_package", elapsed, first_progress)
        details["operations"]["export_run_package"] = {"elapsedMs": elapsed, "progressEvents": progress_count}
    finally:
        client.close()
    return records, details


def _load_budget(path: Path) -> dict[str, Any]:
    try:
        budget = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise BenchmarkFailure(f"cannot read performance budget {path}: {error}") from error
    if not isinstance(budget, dict) or budget.get("schemaVersion") != "voxelweave.native-performance-budget.v1":
        raise BenchmarkFailure("performance budget has an unsupported schemaVersion")
    if not isinstance(budget.get("metrics"), dict):
        raise BenchmarkFailure("performance budget metrics must be an object")
    return budget


def _summaries(records: dict[str, list[float]], budget: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    summaries: dict[str, Any] = {}
    failures: list[str] = []
    for metric, samples in sorted(records.items()):
        config = budget.get("metrics", {}).get(metric, {})
        if not isinstance(config, dict):
            config = {}
        p50 = percentile(samples, 0.50)
        p95 = percentile(samples, 0.95)
        maximum = max(samples)
        target = config.get("target_ms")
        gate = config.get("gate_ms")
        target_met = target is None or p95 <= float(target)
        gate_passed = gate is None or p95 <= float(gate)
        if gate is not None and not gate_passed:
            failures.append(f"{metric} p95={p95:.3f}ms exceeds severe-regression gate {float(gate):.3f}ms")
        summaries[metric] = {
            "samplesMs": [round(value, 3) for value in samples],
            "p50Ms": round(p50, 3),
            "p95Ms": round(p95, 3),
            "maxMs": round(maximum, 3),
            "targetMs": target,
            "targetMet": target_met,
            "gateMs": gate,
            "gatePassed": gate_passed,
        }
    return summaries, failures


def run_benchmark(
    *,
    sidecar: Path | None,
    output_dir: Path,
    budget_path: Path,
    iterations: int,
    warmups: int,
    request_timeout_seconds: float,
    allow_non_native: bool = False,
) -> dict[str, Any]:
    machine = platform.machine()
    if (platform.system(), machine) != ("Darwin", "arm64") and not allow_non_native:
        raise BenchmarkFailure("performance qualification requires an Apple Silicon macOS host")
    if iterations <= 0 or warmups < 0:
        raise BenchmarkFailure("iterations must be positive and warmups must be non-negative")
    output_dir.mkdir(parents=True, exist_ok=True)
    if any(output_dir.iterdir()):
        raise BenchmarkFailure(f"output directory must be empty: {output_dir}")
    budget = _load_budget(budget_path)
    if sidecar is not None:
        command = [str(sidecar.resolve())]
    else:
        python_bin = os.environ.get("VOXELWEAVE_PYTHON_BIN", sys.executable)
        command = [python_bin, "-m", "voxelweave.sidecar"]

    all_records: dict[str, list[float]] = {}
    iteration_details: list[dict[str, Any]] = []
    operation_failure: str | None = None
    try:
        for warmup in range(warmups):
            warmup_dir = output_dir / f"warmup-{warmup + 1}"
            warmup_dir.mkdir()
            _run_iteration(command, warmup_dir, request_timeout_seconds)
        for iteration in range(iterations):
            iteration_dir = output_dir / f"iteration-{iteration + 1}"
            iteration_dir.mkdir()
            records, details = _run_iteration(command, iteration_dir, request_timeout_seconds)
            for metric, values in records.items():
                all_records.setdefault(metric, []).extend(values)
            iteration_details.append(details)
    except BenchmarkFailure as error:
        operation_failure = str(error)
    summaries, failures = _summaries(all_records, budget)
    if operation_failure:
        failures.insert(0, operation_failure)
    evidence: dict[str, Any] = {
        "schemaVersion": "voxelweave.native-performance.v1",
        "status": "failed" if failures else "passed",
        "host": {"system": platform.system(), "release": platform.release(), "machine": machine, "processor": platform.processor()},
        "sidecar": "bundled" if sidecar else "python-module",
        "fixture": {"source": "synthetic://voxelweave/native-performance", "shapeZYX": [12, 32, 40], "scientificClaims": "not_established_by_software"},
        "warmups": warmups,
        "iterations": iterations,
        "measurements": summaries,
        "iterationDetails": iteration_details,
        "gateFailures": failures,
        "limitations": [
            "The benchmark measures current Python/sidecar operations and JSONL bridge timing only.",
            "WebKit MPR scrolling, Three.js orbit FPS, geometry interaction FPS, and main-thread task duration require a built app with browser tooling or Instruments and are not claimed here.",
            "Synthetic DICOM timing is a release smoke fixture, not a substitute for representative clinical series qualification.",
        ],
    }
    evidence_path = output_dir / "native-performance.json"
    evidence_path.write_text(json.dumps(evidence, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    if failures:
        raise BenchmarkFailure("; ".join(failures))
    return evidence


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sidecar", type=Path, help="bundled one-file sidecar; omit to use the Python module")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--budget-file", type=Path, default=ROOT / "scripts" / "native-performance-budget.json")
    parser.add_argument("--iterations", type=int, default=3)
    parser.add_argument("--warmups", type=int, default=1)
    parser.add_argument("--request-timeout-seconds", type=float, default=120.0)
    parser.add_argument("--allow-non-native", action="store_true", help="allow controlled fixture runs off Apple Silicon macOS")
    args = parser.parse_args()
    try:
        evidence = run_benchmark(
            sidecar=args.sidecar,
            output_dir=args.output_dir.resolve(),
            budget_path=args.budget_file.resolve(),
            iterations=args.iterations,
            warmups=args.warmups,
            request_timeout_seconds=args.request_timeout_seconds,
            allow_non_native=args.allow_non_native or os.environ.get("VOXELWEAVE_ALLOW_NON_MACOS") == "1",
        )
    except BenchmarkFailure as error:
        print(f"[native-performance] FAIL {error}", file=sys.stderr)
        return 1
    print(f"[native-performance] PASS iterations={evidence['iterations']} metrics={len(evidence['measurements'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
